ANCHOR_DRIFT = '<div id="hts-drift-slot"></div>\n </section>'
ANCHOR_BODY = "</body>"

# Tempered spans of a previously inserted corr section / boot, and of
# the 3D chart section (insertion anchor on pages that carry it). None
# of these can cross another section/script boundary.
CORR_SECTION_RE = re.compile(
    r' <section class="hts-sec(?: htlp-off)?" id="hts-sec-corr">'
    r'(?:(?!</?section).)*</section>', re.S)
# The boot span also matches the ht-lazypanels v1 gated form (the boot
# script rewritten to inert text/plain): baked pages carry the gate, and
# the refresh restores the live boot; patch_lazy_panels re-gates it later
# in the same deploy run.
CORR_BOOT_RE = re.compile(
    r'\n<script(?: type="text/plain" data-htlp-boot="corr")?>\n'
    r'// ht-corr v1 boot(?:(?!</?script).)*</script>', re.S)
SEC3D_RE = re.compile(
    r' <section class="hts-sec" id="hts-sec-3dchart">'
    r'(?:(?!</?section).)*</section>', re.S)
BOOT_PAIR = BOOT.removesuffix("\n</body>")


def post_checks(s: str, had_3d: bool) -> str | None:
    for token in ("ht-statsview v1", "ht-soilsnow v1", "ht-dacp v1",
                  "ht-weekly v1", "ht-uiux v1", "ht-drift-panel",
                  'id="ht-drift-panel"', "window.HT_DATA"):
        if token not in s:
            return f"FAIL post-check missing {token}"
    if had_3d and 'id="hts-sec-3dchart"' not in s:
        return "FAIL post-check: 3D chart section lost"
    if s.count('id="hts-sec-corr"') != 1 or s.count('id="htcorr-root"') != 1:
        return "FAIL post-check: corr section/root duplication"
    if s.count(MARKER) != 2:
        return f"FAIL post-check: marker count {s.count(MARKER)} (want 2)"
    return None


def patch(path: Path) -> str:
    s = path.read_text(encoding="utf-8")
    site = path.stem.replace("USGS-", "")
    had_3d = 'id="hts-sec-3dchart"' in s
    if MARKER in s:
        secs = CORR_SECTION_RE.findall(s)
        boots = CORR_BOOT_RE.findall(s)
        if len(secs) != 1 or len(boots) != 1:
            return (f"FAIL refresh anchors: {len(secs)} section(s), "
                    f"{len(boots)} boot(s)")
        if "<section" in boots[0] or "ht-drift" in boots[0]:
            return "FAIL refresh boot span over-matched; refusing to write"
        s2 = CORR_SECTION_RE.sub(
            lambda _: SECTION.lstrip("\n").replace("__SITE__", site), s, count=1)
        s2 = CORR_BOOT_RE.sub(lambda _: BOOT_PAIR, s2, count=1)
        if s2 == s:
            return "skip (marker)"
        bad = post_checks(s2, had_3d)
        if bad:
            return bad
        path.write_text(s2, encoding="utf-8")
        return "refreshed"
    if "ht-statsview v1" not in s:
        return "skip (not a Data view page)"
    if s.count(ANCHOR_BODY) != 1:
        return f"FAIL anchor body: {s.count(ANCHOR_BODY)} occurrences"
    if had_3d:
        m = SEC3D_RE.search(s)
        if not m:
            return "FAIL anchor: 3D chart section span not found"
        s = s[:m.end()] + SECTION.replace("__SITE__", site) + s[m.end():]
    else:
        if s.count(ANCHOR_DRIFT) != 1:
            return f"FAIL anchor drift: {s.count(ANCHOR_DRIFT)} occurrences"
        s = s.replace(ANCHOR_DRIFT, ANCHOR_DRIFT + SECTION.replace("__SITE__", site), 1)
    s = s.replace(ANCHOR_BODY, BOOT, 1)
    bad = post_checks(s, had_3d)
    if bad:
        return bad
    path.write_text(s, encoding="utf-8")
    return "patched"


def main():
    root = Path("stations")
    files = sorted(p for p in root.glob("USGS-*.html") if not p.name.endswith("-3d.html"))
    if not files:
        print("no classic station pages found under stations/", file=sys.stderr)
        return 1
    bad = 0
    for p in files:
        r = patch(p)
        print(f"{p.name}: {r}")
        if r.startswith("FAIL"):
            bad += 1
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
