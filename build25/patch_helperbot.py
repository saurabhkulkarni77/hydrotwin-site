#!/usr/bin/env python3
"""ht-helperbot v1: inject the helper-bot widget script into every
station page (classic + 3D) and the home page.

The widget itself lives once in helper/ht-helper.js and its site
index in helper/ht-index.json (generated by gen_helper_index.py);
this patcher only adds one deferred script tag before </body>.
Idempotent: pages already carrying the marker are skipped.
Run from the repo root: python3 build25/patch_helperbot.py
"""
import sys
from pathlib import Path

MARKER = "ht-helperbot v1"


def tag(prefix: str) -> str:
    return (f'\n<!-- {MARKER} -->\n'
            f'<script src="{prefix}helper/ht-helper.js" defer></script>\n</body>')


def patch(path: Path, prefix: str) -> str:
    s = path.read_text(encoding="utf-8")
    if MARKER in s:
        return "skip (marker)"
    if s.count("</body>") != 1:
        return f"FAIL anchor body: {s.count('</body>')} occurrences"
    s = s.replace("</body>", tag(prefix), 1)
    if s.count(MARKER) != 1:
        return "FAIL post-check marker count"
    path.write_text(s, encoding="utf-8")
    return "patched"


def main():
    bad = 0
    files = [(Path("index.html"), "")]
    files += [(p, "../") for p in sorted(Path("stations").glob("USGS-*.html"))]
    for p, prefix in files:
        if not p.exists():
            print(f"{p}: missing", file=sys.stderr)
            bad += 1
            continue
        r = patch(p, prefix)
        print(f"{p}: {r}")
        if r.startswith("FAIL"):
            bad += 1
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
